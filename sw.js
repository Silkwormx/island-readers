/* GitHub Pages serves .mp3 as "audio/mp3", which Safari does not accept for media: always answer with audio/mpeg */
function fixMime(res, url) {
  if (!/\.mp3$/.test(url.pathname)) return res;
  const hd = new Headers(res.headers); hd.set('Content-Type', 'audio/mpeg');
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers: hd });
}
async function ranged(req, res) {
  const m = /bytes=(\d*)-(\d*)/.exec(req.headers.get('range') || '');
  const buf = await res.arrayBuffer(); const size = buf.byteLength;
  let s = m && m[1] ? parseInt(m[1], 10) : 0; let e2 = m && m[2] ? parseInt(m[2], 10) : size - 1;
  if (e2 >= size) e2 = size - 1;
  return new Response(buf.slice(s, e2 + 1), { status: 206, headers: {
    'Content-Type': /\.mp3$/.test(new URL(req.url).pathname) ? 'audio/mpeg' : (res.headers.get('Content-Type') || 'application/octet-stream'),
    'Content-Range': 'bytes ' + s + '-' + e2 + '/' + size, 'Content-Length': String(e2 - s + 1), 'Accept-Ranges': 'bytes' } });
}
self.addEventListener('fetch', (e) => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin) return;
  if (req.mode === 'navigate' || isCode(url)) {
    e.respondWith((async () => {
      try {
        const net = await fetch(req.mode === 'navigate' ? new Request(req.url, { cache: 'no-cache', credentials: 'same-origin' }) : new Request(req.url, { cache: 'no-cache', credentials: 'same-origin' }));
        if (net && net.ok) { const c = await caches.open(CACHE); c.put(req.mode === 'navigate' ? './index.html' : req, net.clone()); }
        return net;
      } catch (err) {
        const hit = (await caches.match(req, { ignoreSearch: true })) || (req.mode === 'navigate' ? await caches.match('./index.html') : null);
        if (hit) return hit; return Response.error();
      }
    })());
    return;
  }
  e.respondWith((async () => {
    const hit = await caches.match(req, { ignoreSearch: true });
    if (hit) return req.headers.has('range') ? ranged(req, hit) : fixMime(hit, url);
    /* <audio> asks for byte ranges, and a 206 reply was never cached, so sounds were missing offline.
       Fetch the whole clip once, keep it, and answer the range from it. */
    if (req.headers.has('range') && /\.mp3$/.test(url.pathname)) {
      try {
        const full = await fetch(url.href, { credentials: 'same-origin' });
        if (full && full.ok && full.status === 200) { const c = await caches.open(CACHE); c.put(url.href, full.clone()); return ranged(req, full); }
      } catch (err) { /* fall through to the network */ }
    }
    const net = await fetch(req);
    if (net && net.ok && net.status === 200 && !req.headers.has('range')) { const c = await caches.open(CACHE); c.put(req, net.clone()); }
    return fixMime(net, url);
  })());
});
